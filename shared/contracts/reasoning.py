"""Case findings, factor, citation, and precedent contracts for Sentinel V1."""

from datetime import datetime
from enum import Enum
from pydantic import BaseModel, ConfigDict

from shared.contracts.detection import RiskBand


class Materiality(str, Enum):
    """Materiality weight of an evidence factor."""

    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class FindingFactor(BaseModel):
    """Specific supporting or counter factual claim analyzed during reasoning."""

    model_config = ConfigDict(extra="forbid")

    statement: str
    fact_ids: list[str]
    materiality: Materiality


class Citation(BaseModel):
    """Citation linking a finding claim back to facts and optional precedents."""

    model_config = ConfigDict(extra="forbid")

    claim_id: str
    fact_ids: list[str]
    precedent_ids: list[str] | None = None


class RecommendedDisposition(str, Enum):
    """Advisory recommendation generated by Gemini reasoning.

    BLOCK_HOLD is purely advisory and carries no automated execution authority.
    """

    CLEAR = "CLEAR"
    ESCALATE = "ESCALATE"
    BLOCK_HOLD = "BLOCK_HOLD"


class CaseFindings(BaseModel):
    """Structured findings output produced by Gemini reasoning."""

    model_config = ConfigDict(extra="forbid")

    findings_id: str
    case_id: str
    risk_assessment: RiskBand
    summary: str
    supporting_factors: list[FindingFactor]
    counter_factors: list[FindingFactor]
    evidence_gaps: list[str]
    evidence_citations: list[Citation]
    recommended_disposition: RecommendedDisposition
    generated_at: datetime
    model_name: str
    model_version: str
    prompt_version: str


class Precedent(BaseModel):
    """Historical case precedent retrieved for comparative investigation."""

    model_config = ConfigDict(extra="forbid")

    precedent_id: str
    case_summary: str
    anomaly_tags: list[str]
    outcome: str
    evidence_summary: str
    source_type: str
    created_at: datetime
