"""Case findings, factor, and citation contracts for Sentinel V1.

No Precedent contract: V1 has no RAG / precedent retrieval (Contracts
V1-Scoped S0/S14) -- that is a named, deferred V2 upgrade, not built here."""

from datetime import datetime
from enum import Enum
from pydantic import BaseModel, ConfigDict

from shared.contracts.detection import DetectionOutput, RiskBand
from shared.contracts.evidence import EvidenceBundle
from shared.contracts.transaction import Transaction


class Materiality(str, Enum):
    """Materiality weight of an evidence factor."""

    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class FindingFactor(BaseModel):
    """Specific supporting or counter factual claim analyzed during reasoning."""

    model_config = ConfigDict(extra="forbid")

    statement: str
    fact_ids: list[str]
    materiality: Materiality


class Citation(BaseModel):
    """Citation linking a finding claim back to the evidence facts that support it.

    No precedent_ids field: V1 has no RAG / precedent retrieval (Contracts
    V1-Scoped S14)."""

    model_config = ConfigDict(extra="forbid")

    claim_id: str
    fact_ids: list[str]


class RecommendedDisposition(str, Enum):
    """Advisory recommendation generated by Gemini reasoning.

    BLOCK_HOLD is purely advisory and carries no automated execution authority.
    """

    CLEAR = "CLEAR"
    ESCALATE = "ESCALATE"
    BLOCK_HOLD = "BLOCK_HOLD"


class CaseFindings(BaseModel):
    """Structured findings output produced by Gemini reasoning."""

    model_config = ConfigDict(extra="forbid")

    findings_id: str
    case_id: str
    risk_assessment: RiskBand
    summary: str
    supporting_factors: list[FindingFactor]
    counter_factors: list[FindingFactor]
    evidence_gaps: list[str]
    evidence_citations: list[Citation]
    recommended_disposition: RecommendedDisposition
    generated_at: datetime
    model_name: str
    model_version: str
    prompt_version: str


class ReasoningInput(BaseModel):
    """Input contract for invoking Reasoning (Build Checklist Phase 3.1's
    "ReasoningInput assembly": transaction, detection output, full evidence
    bundle, and prompt version, mirroring EvidenceAgentInput's pattern)."""

    model_config = ConfigDict(extra="forbid")

    case_id: str
    transaction: Transaction
    detection: DetectionOutput
    evidence_bundle: EvidenceBundle
    prompt_version: str


class ReasoningStatus(str, Enum):
    """Outcome of one bounded Reasoning call.

    FAILED means no CaseFindings exists for Policy to evaluate -- none of
    Policy's named rules (Contracts V1-Scoped S16, Phase 4) can match without
    findings.risk_assessment, so the case falls through to the Otherwise
    rule -> ESCALATE. Reached only after the single citation/schema reprompt
    (S14) is exhausted, never a silent drop (Safety Invariant 10).
    """

    SUCCESS = "SUCCESS"
    FAILED = "FAILED"


class ReasoningOutput(BaseModel):
    """Output contract produced by Reasoning, mirroring EvidenceAgentOutput's
    result-plus-trace shape. findings is populated only when status=SUCCESS."""

    model_config = ConfigDict(extra="forbid")

    status: ReasoningStatus
    findings: CaseFindings | None
    attempts: int
    failure_reasons: list[str]
    model_name: str
    model_version: str
