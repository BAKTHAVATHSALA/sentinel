"""Detection contract and associated domain enums for Sentinel V1."""

from datetime import datetime
from decimal import Decimal
from enum import Enum
from pydantic import BaseModel, ConfigDict


class RiskBand(str, Enum):
    """Categorical risk band assessed for transactions and findings."""

    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"


class AnomalyTag(str, Enum):
    """Categorical anomaly indicators identified during initial detection."""

    NEW_DEVICE = "NEW_DEVICE"
    UNUSUAL_LOCATION = "UNUSUAL_LOCATION"
    IMPOSSIBLE_TRAVEL = "IMPOSSIBLE_TRAVEL"
    UNUSUAL_AMOUNT = "UNUSUAL_AMOUNT"
    UNUSUAL_TIME = "UNUSUAL_TIME"
    MERCHANT_RISK = "MERCHANT_RISK"
    LINKED_ENTITY_ANOMALY = "LINKED_ENTITY_ANOMALY"
    KYC_ANOMALY = "KYC_ANOMALY"


class DetectionOutput(BaseModel):
    """Output generated by the deterministic/ML detection service."""

    model_config = ConfigDict(extra="forbid")

    case_id: str
    transaction_id: str
    risk_score: Decimal
    risk_band: RiskBand
    anomaly_tags: list[AnomalyTag]
    detection_reasons: list[str]
    model_name: str
    model_version: str
    detected_at: datetime
